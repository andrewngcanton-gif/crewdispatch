// autostart-windows.ts — the Windows-specific half of the Dashboard autostart.
//
// Chosen mechanism: a single user-scoped value under
//
//   HKCU\Software\Microsoft\Windows\CurrentVersion\Run\JobQuayDashboard
//
// pointing at a generated Windows Script Host shim inside the installation:
//
//   "<SystemRoot>\System32\wscript.exe" //B //NoLogo "<install>\autostart\jobquay-dashboard.vbs"
//
// Why this is the right mechanism here:
//   * it is user-scoped (HKCU) — no elevation, no service, no machine-wide
//     change, and no other user's session is affected;
//   * it is exactly one identifiable value with a CrewDispatch-owned name, so it
//     can be inspected (`reg query`) and removed (`reg delete`) without
//     touching anything else in the Run key;
//   * wscript.exe is a GUI host, so Windows creates no console window for the
//     registration itself, and the shim starts the installed CLI with window
//     style 0 (hidden) so no PowerShell/cmd window ever appears at login;
//   * the shim lives INSIDE the installation, so the registered entry always
//     targets that installed artifact and disappears with it.
//
// Everything OS-specific lives in this file; `src/install/autostart.ts` holds
// the platform-agnostic orchestration. A future macOS implementation would be
// a sibling module and must not claim support here.
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { resolveUserNodeRuntime } from "./node-runtime";

export const AUTOSTART_MECHANISM_ID = "windows-hkcu-run";
export const AUTOSTART_VALUE_NAME = "JobQuayDashboard";
export const AUTOSTART_RUN_KEY = "HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Run";
export const AUTOSTART_DIR_NAME = "autostart";
export const AUTOSTART_SCRIPT_NAME = "jobquay-dashboard.vbs";
export const AUTOSTART_METADATA_NAME = "jobquay-dashboard.json";
export const AUTOSTART_METADATA_FORMAT_VERSION = 1;

export interface AutostartPayloadInput {
  /** Node runtime the installed CLI is launched with (default: this process). */
  nodePath?: string;
}

export interface AutostartPayload {
  shimPath: string;
  metadataPath: string;
  changed: boolean;
}

export function autostartDir(installRoot: string): string {
  return path.join(installRoot, AUTOSTART_DIR_NAME);
}

export function autostartShimPath(installRoot: string): string {
  return path.join(autostartDir(installRoot), AUTOSTART_SCRIPT_NAME);
}

export function autostartMetadataPath(installRoot: string): string {
  return path.join(autostartDir(installRoot), AUTOSTART_METADATA_NAME);
}

/** Resolve the Windows Script Host executable from the installer's environment. */
export function resolveWscriptPath(env: NodeJS.ProcessEnv = process.env): string {
  return path.win32.join(env.SystemRoot || env.WINDIR || "C:\\Windows", "System32", "wscript.exe");
}

/**
 * The exact command line stored in the Run value. It is fully quoted, uses the
 * GUI script host (never a console host), and points only at the installed
 * artifact's own shim.
 */
export function renderAutostartCommand(shimPath: string, env: NodeJS.ProcessEnv = process.env): string {
  return `"${resolveWscriptPath(env)}" //B //NoLogo "${shimPath}"`;
}

function assertSafeLiteral(value: string, label: string): void {
  if (value.includes('"') || /[\r\n]/.test(value)) {
    throw new Error(`${label} contains characters that cannot be embedded in the autostart shim: ${JSON.stringify(value)}`);
  }
}

export function renderAutostartMetadata(installRoot: string, nodePath: string): string {
  const metadata = {
    product: "jobquay",
    kind: "jobquay-dashboard-autostart",
    formatVersion: AUTOSTART_METADATA_FORMAT_VERSION,
    installRoot,
    nodePath,
    cliEntry: path.join(installRoot, "dist", "cli", "jobquay-cli.js")
  };
  return `${JSON.stringify(metadata, null, 2)}\n`;
}

/**
 * The generated shim. It is a GUI-host script: no console is created for it,
 * and it starts the installed CLI hidden (window style 0) in the headless
 * `autostart run` mode that reuses/ensures the Hub without opening a browser.
 * If the runtime or CLI entry is missing it records a local diagnostic under
 * the CrewDispatch data root instead of failing silently.
 */
export function renderAutostartShim(installRoot: string, nodePath: string): string {
  assertSafeLiteral(installRoot, "install root");
  assertSafeLiteral(nodePath, "node runtime path");
  const lines = [
    "' CrewDispatch Dashboard autostart shim — generated by the CrewDispatch installer.",
    "' Registered as the user-scoped value \"JobQuayDashboard\" under",
    "' HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Run. It launches the",
    "' installed CrewDispatch CLI in headless Dashboard-ensure mode with no visible",
    "' console window and never opens a browser.",
    "Option Explicit",
    "",
    "Dim shell, fso, installRoot, nodeExe, cliEntry, commandLine, exitCode",
    "Dim dataRoot, logDir, logFile, logStream",
    "",
    `installRoot = "${installRoot}"`,
    `nodeExe = "${nodePath}"`,
    "cliEntry = installRoot & \"\\dist\\cli\\jobquay-cli.js\"",
    "",
    "Set fso = CreateObject(\"Scripting.FileSystemObject\")",
    "Set shell = CreateObject(\"WScript.Shell\")",
    "",
    "If Not fso.FileExists(nodeExe) Then",
    "  WriteShimLog \"node runtime missing: \" & nodeExe",
    "  WScript.Quit 3",
    "End If",
    "If Not fso.FileExists(cliEntry) Then",
    "  WriteShimLog \"CrewDispatch CLI entry missing: \" & cliEntry",
    "  WScript.Quit 4",
    "End If",
    "",
    "commandLine = \"\"\"\" & nodeExe & \"\"\" \"\"\" & cliEntry & \"\"\" autostart run\"",
    "exitCode = shell.Run(commandLine, 0, True)",
    "If exitCode <> 0 Then WriteShimLog \"jobquay autostart run exited with code \" & exitCode",
    "WScript.Quit exitCode",
    "",
    "Sub WriteShimLog(message)",
    "  On Error Resume Next",
    "  dataRoot = shell.ExpandEnvironmentStrings(\"%JOBQUAY_DATA_ROOT%\")",
    "  If dataRoot = \"%JOBQUAY_DATA_ROOT%\" Then dataRoot = \"\"",
    "  If Len(dataRoot) = 0 Then",
    "    dataRoot = fso.BuildPath(shell.ExpandEnvironmentStrings(\"%LOCALAPPDATA%\"), \"CrewDispatch\")",
    "  End If",
    "  logDir = fso.BuildPath(dataRoot, \"autostart\")",
    "  If Not fso.FolderExists(logDir) Then fso.CreateFolder logDir",
    "  logFile = fso.BuildPath(logDir, \"shim.log\")",
    "  Set logStream = fso.OpenTextFile(logFile, 8, True)",
    "  logStream.WriteLine Date & \" \" & Time & \" \" & message",
    "  logStream.Close",
    "  On Error GoTo 0",
    "End Sub",
    ""
  ];
  return lines.join("\r\n");
}

function writeIfChanged(file: string, content: string): boolean {
  try {
    if (fs.readFileSync(file, "utf8") === content) return false;
  } catch {
    /* missing or unreadable: rewrite */
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content, "utf8");
  return true;
}

/**
 * Write the shim + metadata into a payload root (the installer stage during
 * install/upgrade, or the installation itself for a self-heal). `installRoot`
 * is the FINAL installation directory: the stage is renamed into place, so the
 * recorded paths must be the final ones.
 */
export function writeAutostartPayload(payloadRoot: string, installRoot: string, input: AutostartPayloadInput = {}): AutostartPayload {
  const nodePath = input.nodePath ?? resolveUserNodeRuntime(process.env, "win32")?.path ?? process.execPath;
  const shimPath = path.join(payloadRoot, AUTOSTART_DIR_NAME, AUTOSTART_SCRIPT_NAME);
  const metadataPath = path.join(payloadRoot, AUTOSTART_DIR_NAME, AUTOSTART_METADATA_NAME);
  const shimChanged = writeIfChanged(shimPath, renderAutostartShim(installRoot, nodePath));
  const metadataChanged = writeIfChanged(metadataPath, renderAutostartMetadata(installRoot, nodePath));
  return {
    shimPath: autostartShimPath(installRoot),
    metadataPath: autostartMetadataPath(installRoot),
    changed: shimChanged || metadataChanged
  };
}

/** Split a Windows command line into tokens, honouring double quotes. */
export function tokenizeCommandLine(command: string): string[] {
  const tokens: string[] = [];
  let current = "";
  let started = false;
  let quoted = false;
  for (const ch of command) {
    if (ch === '"') {
      quoted = !quoted;
      started = true;
      continue;
    }
    if (!quoted && /\s/.test(ch)) {
      if (started) {
        tokens.push(current);
        current = "";
        started = false;
      }
      continue;
    }
    current += ch;
    started = true;
  }
  if (started) tokens.push(current);
  return tokens;
}

export interface ParsedAutostartCommand {
  tokens: string[];
  executable: string | null;
  shimPath: string | null;
  installRoot: string | null;
}

/**
 * Parse a registered command line and recognise the CrewDispatch-owned shape
 * (`wscript ... "<install>\autostart\jobquay-dashboard.vbs"`). Recognition is
 * what makes removal safe: a value that does not look like ours is never
 * deleted.
 */
export function parseAutostartCommand(command: string): ParsedAutostartCommand {
  const tokens = tokenizeCommandLine(command);
  const executable = tokens.length > 0 ? tokens[0]! : null;
  let shimPath: string | null = null;
  for (const token of tokens.slice(1)) {
    if (path.win32.basename(token).toLowerCase() === AUTOSTART_SCRIPT_NAME.toLowerCase()
      && path.win32.basename(path.win32.dirname(token)).toLowerCase() === AUTOSTART_DIR_NAME.toLowerCase()) {
      shimPath = token;
      break;
    }
  }
  return {
    tokens,
    executable,
    shimPath,
    installRoot: shimPath ? path.win32.dirname(path.win32.dirname(shimPath)) : null
  };
}

export function isJobQuayAutostartCommand(command: string): boolean {
  return parseAutostartCommand(command).shimPath !== null;
}

