export type RegistryRead = { ok: true; value: string | null } | { ok: false; error: string };
export type RegistryWrite = { ok: true } | { ok: false; error: string };
export type RegistryRemove = { ok: true; removed: boolean } | { ok: false; error: string };

/**
 * The small boundary around "the Run value". The real implementation shells
 * out to `reg.exe`; automated tests use the emulated-file implementation via
 * the TEST-ONLY `JOBQUAY_TEST_AUTOSTART_REGISTRY` env seam so they never write
 * a real login entry on the operator's account.
 */
export interface AutostartRegistry {
  readonly kind: "windows-registry" | "emulated-file";
  read(name: string): RegistryRead;
  write(name: string, value: string): RegistryWrite;
  remove(name: string): RegistryRemove;
}

function runReg(regExe: string, args: string[]): { status: number | null; stdout: string; stderr: string; error: string | null } {
  const result = spawnSync(regExe, args, { encoding: "utf8", windowsHide: true });
  return {
    status: result.status,
    stdout: result.stdout ?? "",
    stderr: result.stderr ?? "",
    error: result.error ? result.error.message : null
  };
}

function unescapeRegString(raw: string): string {
  let out = "";
  for (let index = 0; index < raw.length; index += 1) {
    const ch = raw[index]!;
    if (ch === "\\" && index + 1 < raw.length) {
      index += 1;
      out += raw[index]!;
      continue;
    }
    out += ch;
  }
  return out;
}

/**
 * Read one REG_SZ value out of a `reg export` file. The export format is
 * UTF-16LE (handled by the caller) and escapes `\` and `"` with a backslash:
 *
 *   [HKEY_CURRENT_USER\...\Run]
 *   "JobQuayDashboard"="\"C:\\Windows\\...\\wscript.exe\" //B ..."
 */
export function parseExportedRegValue(text: string, name: string): string | null {
  const normalizedName = name.toLowerCase();
  for (const line of text.split(/\r?\n/)) {
    const match = /^"([^"\\]*)"=(.*)$/.exec(line.trim());
    if (!match) continue;
    if (match[1]!.toLowerCase() !== normalizedName) continue;
    const raw = match[2]!.trim();
    if (raw.startsWith('"') && raw.endsWith('"') && raw.length >= 2) {
      return unescapeRegString(raw.slice(1, -1));
    }
    return raw.length ? raw : null;
  }
  return null;
}

/**
 * The real, user-scoped HKCU Run implementation. No elevation is required.
 *
 * Reads use `reg export` + the UTF-16LE export file instead of `reg query`:
 * reg.exe writes query output in the legacy console codepage, which would
 * mangle a non-ASCII installation path, while the export file preserves the
 * stored Unicode value exactly.
 */
export function windowsRunKeyRegistry(env: NodeJS.ProcessEnv = process.env): AutostartRegistry {
  const candidate = path.win32.join(env.SystemRoot || env.WINDIR || "C:\\Windows", "System32", "reg.exe");
  const regExe = fs.existsSync(candidate) ? candidate : "reg.exe";
  return {
    kind: "windows-registry",
    read(name) {
      const temp = path.join(
        os.tmpdir(),
        `jobquay-autostart-${process.pid}-${Date.now()}-${Math.random().toString(16).slice(2)}.reg`
      );
      try {
        const exported = runReg(regExe, ["export", AUTOSTART_RUN_KEY, temp, "/y"]);
        if (exported.error) return { ok: false, error: exported.error };
        if (exported.status === 0) {
          let text: string;
          try {
            text = fs.readFileSync(temp, "utf16le").replace(/^\uFEFF/, "");
          } catch (error) {
            return { ok: false, error: String((error as Error)?.message || error) };
          }
          return { ok: true, value: parseExportedRegValue(text, name) };
        }
        // The export failed: a missing Run key means "no value", anything else
        // (permissions, unexpected reg.exe failure) is a real error.
        const key = runReg(regExe, ["query", AUTOSTART_RUN_KEY]);
        if (key.error) return { ok: false, error: key.error };
        if (key.status !== 0) return { ok: true, value: null };
        return { ok: false, error: (exported.stderr || exported.stdout).trim() || `reg export exited with ${exported.status}` };
      } finally {
        try {
          fs.rmSync(temp, { force: true });
        } catch {
          /* the temp file may not have been created */
        }
      }
    },
    write(name, value) {
      const result = runReg(regExe, ["add", AUTOSTART_RUN_KEY, "/v", name, "/t", "REG_SZ", "/d", value, "/f"]);
      if (result.error) return { ok: false, error: result.error };
      if (result.status !== 0) return { ok: false, error: (result.stderr || result.stdout).trim() || `reg add exited with ${result.status}` };
      return { ok: true };
    },
    remove(name) {
      const result = runReg(regExe, ["delete", AUTOSTART_RUN_KEY, "/v", name, "/f"]);
      if (result.error) return { ok: false, error: result.error };
      if (result.status === 0) return { ok: true, removed: true };
      const verify = runReg(regExe, ["query", AUTOSTART_RUN_KEY, "/v", name]);
      if (verify.error) return { ok: false, error: verify.error };
      if (verify.status !== 0) return { ok: true, removed: false };
      return { ok: false, error: (result.stderr || result.stdout).trim() || `reg delete exited with ${result.status}` };
    }
  };
}

interface EmulatedRegistryData {
  product: "jobquay-test-autostart-registry";
  values: Record<string, string>;
}

function readEmulated(file: string): { ok: true; values: Record<string, string> } | { ok: false; error: string } {
  let raw: string;
  try {
    raw = fs.readFileSync(file, "utf8");
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return { ok: true, values: {} };
    return { ok: false, error: String((error as Error)?.message || error) };
  }
  try {
    const parsed = JSON.parse(raw) as Partial<EmulatedRegistryData>;
    if (!parsed || parsed.product !== "jobquay-test-autostart-registry" || typeof parsed.values !== "object" || parsed.values === null) {
      return { ok: false, error: "the emulated autostart registry file has an unsupported shape" };
    }
    return { ok: true, values: { ...(parsed.values as Record<string, string>) } };
  } catch (error) {
    return { ok: false, error: String((error as Error)?.message || error) };
  }
}

function writeEmulated(file: string, values: Record<string, string>): { ok: true } | { ok: false; error: string } {
  try {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    const data: EmulatedRegistryData = { product: "jobquay-test-autostart-registry", values };
    fs.writeFileSync(file, `${JSON.stringify(data, null, 2)}\n`, "utf8");
    return { ok: true };
  } catch (error) {
    return { ok: false, error: String((error as Error)?.message || error) };
  }
}

/**
 * TEST-ONLY emulation of the HKCU Run key backed by one JSON file. It exists so
 * installer/lifecycle acceptance can prove the exact registered command and
 * its removal without ever touching the operator's real login entries.
 */
export function emulatedRegistryFile(file: string): AutostartRegistry {
  const resolved = path.resolve(file);
  return {
    kind: "emulated-file",
    read(name) {
      const data = readEmulated(resolved);
      if (!data.ok) return { ok: false, error: data.error };
      const value = data.values[name];
      return { ok: true, value: typeof value === "string" ? value : null };
    },
    write(name, value) {
      const data = readEmulated(resolved);
      if (!data.ok) return { ok: false, error: data.error };
      data.values[name] = value;
      return writeEmulated(resolved, data.values);
    },
    remove(name) {
      const data = readEmulated(resolved);
      if (!data.ok) return { ok: false, error: data.error };
      if (!(name in data.values)) return { ok: true, removed: false };
      delete data.values[name];
      const written = writeEmulated(resolved, data.values);
      return written.ok ? { ok: true, removed: true } : written;
    }
  };
}

export const AUTOSTART_REGISTRY_SEAM_ENV = "JOBQUAY_TEST_AUTOSTART_REGISTRY";

export function resolveAutostartRegistry(env: NodeJS.ProcessEnv = process.env): AutostartRegistry {
  const seam = typeof env[AUTOSTART_REGISTRY_SEAM_ENV] === "string" ? env[AUTOSTART_REGISTRY_SEAM_ENV]!.trim() : "";
  if (seam) return emulatedRegistryFile(seam);
  return windowsRunKeyRegistry(env);
}
